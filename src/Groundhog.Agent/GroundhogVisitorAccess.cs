using Groundhog.Protocol;

namespace Groundhog.Agent;

/// <summary>
/// A tunnel's visitor access rules, declared by the agent so they live with the app's configuration: who may visit
/// by default, per path, from which IP ranges, and with which visitor tokens.
/// </summary>
/// <remarks>
/// <para>
/// The agent sends the rules on every connection; the relay stores them unless the tunnel's visitor access is
/// managed in the dashboard. Visitor tokens are given here as plaintext, from a secret source, and only their
/// SHA-256 hashes are sent.
/// </para>
/// <para>Values use <see cref="VisitorAccessMethods"/>: <c>anyone</c>, <c>members</c>, <c>tokens</c> and <c>ips</c>.</para>
/// </remarks>
/// <example>
/// <code>
/// VisitorAccess = new GroundhogVisitorAccess
/// {
///     Allow = [VisitorAccessMethods.Members],
///     Rules = [new VisitorAccessPathRule("/webhooks", [VisitorAccessMethods.Anyone])],
/// },
/// </code>
/// </example>
public sealed class GroundhogVisitorAccess
{
    /// <summary>Who may visit paths no rule matches. Defaults to <c>anyone</c>.</summary>
    public IReadOnlyList<string> Allow { get; init; } = [VisitorAccessMethods.Anyone];

    /// <summary>Path rules: the longest matching path prefix wins.</summary>
    public IReadOnlyList<VisitorAccessPathRule> Rules { get; init; } = [];

    /// <summary>IP ranges in CIDR form for <c>ips</c>, for example <c>203.0.113.0/24</c>.</summary>
    public IReadOnlyList<string> IpRanges { get; init; } = [];

    /// <summary>
    /// Visitor tokens for <c>tokens</c>, each 43 base64url characters (for example from
    /// <see cref="VisitorToken.Generate"/>). Only their hashes leave the machine.
    /// </summary>
    public IReadOnlyList<string> Tokens { get; init; } = [];

    /// <summary>
    /// The declaration the agent sends: the rules, with each token replaced by its hash.
    /// </summary>
    /// <exception cref="ArgumentException">The rules are invalid; the message never contains a token.</exception>
    public VisitorAccessDeclaration ToDeclaration()
    {
        foreach (var token in Tokens ?? [])
        {
            if (!VisitorToken.IsWellFormed(token))
            {
                throw new ArgumentException(
                    $"Visitor tokens must be {VisitorToken.Length} base64url characters, as generated by Groundhog.",
                    nameof(Tokens));
            }
        }

        var declaration = new VisitorAccessDeclaration
        {
            Default = new VisitorAccessRule(Allow is null ? [] : [.. Allow]),
            Rules = Rules is null ? [] : [.. Rules],
            IpRanges = IpRanges is null ? [] : [.. IpRanges],
            TokenHashes = Tokens is null ? [] : [.. Tokens.Distinct(StringComparer.Ordinal).Select(VisitorToken.Hash)],
        };

        if (!declaration.TryValidate(out var error))
        {
            throw new ArgumentException($"Visitor access: {error}", nameof(GroundhogAgentOptions.VisitorAccess));
        }

        if (declaration.Encode().Length > VisitorAccessDeclaration.MaxEncodedLength)
        {
            throw new ArgumentException("Visitor access: the rules are too large to send.", nameof(GroundhogAgentOptions.VisitorAccess));
        }

        return declaration;
    }

    /// <summary>Describes the rules without the tokens.</summary>
    public override string ToString() =>
        $"{nameof(GroundhogVisitorAccess)} {{ Allow = {string.Join(",", Allow ?? [])}, Rules = {Rules?.Count ?? 0}, "
        + $"IpRanges = {IpRanges?.Count ?? 0}, Tokens = {Tokens?.Count ?? 0} }}";
}
